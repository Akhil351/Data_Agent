from typing import Annotated, Literal
from operator import add

from langchain_core.messages import AnyMessage
from pydantic import BaseModel, Field


class AgentSchema(BaseModel):
    messages: Annotated[list[AnyMessage], add] = Field(
        default_factory=list,
        description="Messages processed by the agent",
    )

    user_question: str = Field(
        ..., description="The original question asked by the user"
    )
    curated_question: str = Field(
        ..., description="Curated question generated by the agent"
    )
    prompt_query_context: str = Field(
        ..., description="Prompt containing SQL database context"
    )
    generated_sql_query: str = Field(
        ..., description="SQL query generated by the agent"
    )
    is_safe: Literal["Yes", "No"] = Field(
        ..., description="Whether the SQL query is safe"
    )
    comments: str = Field(
        ..., description="Comments regarding the safety of the generated SQL query"
    )
    sql_query_execution_result: str = Field(
        ..., description="SQL query execution result"
    )
    final_answer: str = Field(..., description="Final answer generated by the agent")


class JudgeSchema(BaseModel):
    answer: Literal["Yes", "No"] = Field(
        ...,
        description="Indicates whether the generated SQL query is safe to execute or not",
    )
    comments: str = Field(
        ...,
        description="Additional comments or feedback from the judge regarding the SQL query",
    )


class ETLAgentSchema(BaseModel):
    messages: Annotated[list, add] = Field(
        ..., description="List of messages to be processed by the ETL agent"
    )
